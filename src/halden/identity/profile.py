"""What in the account data could tell two accounts apart, or join them? Read-only.

    python -m halden.identity.profile [--db data/warehouse.duckdb] [--out project_02_identity/profiling_report.md]

Uses the warehouse only, not the ground truth.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import duckdb

from . import matching


def _shared(acc, col: str) -> tuple[int, int, int]:
    s = acc[acc[col].astype(str) != ""][col].dropna()
    vc = s.value_counts()
    vc = vc[vc > 1]
    return len(vc), int(vc.sum()), int(vc.max()) if len(vc) else 0


def profile(db: Path, out: Path) -> None:
    con = duckdb.connect(str(db), read_only=True)
    acc = matching.load_accounts(con)
    shape = lambda p: re.sub(r"\d", "9", p) if isinstance(p, str) else ""
    lines = ["# Profiling report: accounts", "",
             "Generated by `python -m halden.identity.profile` from the project 1 warehouse. Read-only.",
             "Synthetic data.", "",
             f"- Accounts: {len(acc):,} ({(acc.details_from == 'crm').sum():,} from the CRM, "
             f"{(acc.details_from == 'shop_order').sum()} known only from shop orders, because their CRM record "
             "was quarantined in project 1)",
             f"- Accounts with a legacy ID: {acc['legacy_id'].notna().sum():,}",
             f"- First names that are only an initial: {acc['first_is_initial'].sum():,}",
             f"- Names written in capitals: {(acc['last_name'].fillna('').str.isupper()).sum():,}",
             f"- Emails with a capital letter: {(acc['email'].fillna('') != acc['email'].fillna('').str.lower()).sum():,}",
             f"- Phone numbers: {acc['phone'].map(shape).nunique():,} different digit patterns, such as "
             + ", ".join(f"`{p}`" for p in acc['phone'].map(shape).value_counts().index[:5]),
             f"- Phone numbers with no usable key: {(acc['phone_key'] == '').sum():,}", "",
             "## Values shared by more than one account", "",
             "A shared value is a hint, not proof. Two people can share a phone number or a surname.", "",
             "| Key | Values shared | Accounts involved | Most accounts on one value |", "| --- | ---: | ---: | ---: |"]
    for label, col in (("Phone (international digits)", "phone_key"), ("Mailbox (gmail dots and case ignored)", "email_key"),
                       ("Legacy ID", "legacy_id"), ("Postcode", "postcode_key"), ("Surname", "last_key")):
        v, a, mx = _shared(acc, col)
        lines.append(f"| {label} | {v:,} | {a:,} | {mx:,} |")
    raw_v, raw_a, _ = _shared(acc.assign(raw=acc["email"].str.strip()), "raw")
    key_v, key_a, _ = _shared(acc, "email_key")
    lines += ["", f"Matching emails as typed finds {raw_v:,} shared values; after the mailbox key, {key_v:,}.",
              "", "## Candidate pairs by blocking rule", "",
              "| Rule | Pairs |", "| --- | ---: |"]
    pairs = matching.candidate_pairs(con, acc)
    for rule in matching.BLOCKS:
        lines.append(f"| {rule} | {pairs['found_by'].str.contains(rule).sum():,} |")
    lines.append(f"| any rule (each pair once) | {len(pairs):,} |")
    con.close()
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m halden.identity.profile")
    ap.add_argument("--db", type=Path, default=Path("data/warehouse.duckdb"))
    ap.add_argument("--out", type=Path, default=Path("project_02_identity/profiling_report.md"))
    a = ap.parse_args(argv)
    profile(a.db, a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
