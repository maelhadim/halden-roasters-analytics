"""Profile every raw file before writing any loader. Reads only data/raw, changes nothing.

    python -m halden.ingest.profile --raw data/raw --out project_01_ingestion/profiling_report.md

For each source it reports what the files really look like: encoding, delimiter, line
endings, header variants, field counts per line, and file names that break the pattern.
This is the step that found most of the rules the loaders apply.
"""
from __future__ import annotations

import argparse
import csv
import io
import re
from collections import Counter
from pathlib import Path

BOMS = {b"\xff\xfe": "utf-16-le BOM", b"\xfe\xff": "utf-16-be BOM", b"\xef\xbb\xbf": "utf-8 BOM"}
NAME = re.compile(r"^(?P<source>[a-z]+)_(?P<entity>[a-z]+)_(?P<date>\d{8})(?:_(?P<suffix>[a-z0-9]+))?\.(?P<ext>\w+)$")


def detect_encoding(data: bytes) -> str:
    for bom, name in BOMS.items():
        if data.startswith(bom):
            return name
    try:
        data.decode("utf-8")
        return "utf-8" if any(b > 127 for b in data) else "ascii"
    except UnicodeDecodeError:
        return "not utf-8 (8-bit)"


def decode(data: bytes, enc: str) -> str:
    if enc.startswith("utf-16-le"):
        return data[2:].decode("utf-16-le")
    if enc.startswith("not utf-8"):
        return data.decode("cp1252", errors="replace")
    return data.decode("utf-8")


def line_endings(data: bytes, enc: str) -> str:
    crlf = data.count("\r\n".encode("utf-16-le") if enc.startswith("utf-16") else b"\r\n")
    lf = data.count("\n".encode("utf-16-le") if enc.startswith("utf-16") else b"\n")
    if crlf and crlf == lf:
        return "CRLF"
    return "LF" if not crlf else "mixed"


def sniff_delimiter(first_line: str) -> str:
    counts = {d: first_line.count(d) for d in [",", ";", "\t", "|"]}
    return max(counts, key=counts.get)


def profile_source(files: list[Path]) -> dict:
    out = {"files": len(files), "encodings": Counter(), "endings": Counter(), "delims": Counter(),
           "headers": Counter(), "field_counts": Counter(), "physical_vs_records": 0, "odd_names": [],
           "blank_lines": 0, "lines": 0, "unparsable_files": []}
    for p in files:
        m = NAME.match(p.name)
        if not m or m.group("suffix"):
            out["odd_names"].append(p.name)
        data = p.read_bytes()
        enc = detect_encoding(data)
        out["encodings"][enc] += 1
        out["endings"][line_endings(data, enc)] += 1
        text = decode(data, enc)
        lines = text.splitlines()
        out["lines"] += len(lines)
        out["blank_lines"] += sum(1 for ln in lines if not ln.strip())
        if p.suffix == ".jsonl":
            out["delims"]["json lines"] += 1
            continue
        delim = sniff_delimiter(lines[0])
        out["delims"][repr(delim)] += 1
        if delim == "|":
            out["headers"][lines[0].split("|")[0] + "|..|" + lines[0].split("|")[-1]] += 1
            for ln in lines:
                out["field_counts"][(ln[:1], ln.count("|") + 1)] += 1
            continue
        out["headers"][lines[0]] += 1
        try:
            records = list(csv.reader(io.StringIO(text), delimiter=delim))
        except csv.Error as e:
            out["unparsable_files"].append(f"{p.name}: {e}")
            continue
        for r in records[1:]:
            out["field_counts"][len(r)] += 1
        if len(records) != len([ln for ln in lines]):
            out["physical_vs_records"] += 1
    return out


def render(raw: Path) -> str:
    sources = sorted(d.name for d in raw.iterdir() if d.is_dir())
    parts = ["# Profiling report: raw files", "",
             f"Generated by `python -m halden.ingest.profile` from `{raw}`. Read-only; nothing was changed.", ""]
    for s in sources:
        files = sorted((raw / s).iterdir())
        groups: dict[str, list[Path]] = {}
        for p in files:
            m = NAME.match(p.name)
            groups.setdefault(m.group("entity") if m else "?", []).append(p)
        for entity, fs in groups.items():
            r = profile_source(fs)
            parts += [f"## {s} / {entity}", "",
                      f"- Files: {r['files']:,}; physical lines: {r['lines']:,}; blank lines: {r['blank_lines']:,}",
                      f"- Encodings: {dict(r['encodings'])}",
                      f"- Line endings: {dict(r['endings'])}",
                      f"- Delimiters: {dict(r['delims'])}",
                      f"- Header variants: {len(r['headers'])}"]
            for h, n in r["headers"].most_common(5):
                parts.append(f"    - {n:,} files: `{h[:140]}`")
            if r["field_counts"]:
                fc = ", ".join(f"{k}: {v:,}" for k, v in sorted(r["field_counts"].items(), key=str))
                parts.append(f"- Fields per record: {fc}")
            if r["physical_vs_records"]:
                parts.append(f"- Files where CSV records != physical lines (quoted line breaks): "
                             f"{r['physical_vs_records']:,}")
            if r["unparsable_files"]:
                parts.append(f"- Files the csv module could not parse: {len(r['unparsable_files'])}")
                parts += [f"    - {u}" for u in r["unparsable_files"][:5]]
            if r["odd_names"]:
                parts.append(f"- File names outside the plain pattern: {', '.join(r['odd_names'][:10])}")
            parts.append("")
    return "\n".join(parts) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", type=Path, default=Path("data/raw"))
    ap.add_argument("--out", type=Path, default=None)
    a = ap.parse_args(argv)
    text = render(a.raw)
    if a.out:
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_text(text)
    print(text)


if __name__ == "__main__":
    main()
