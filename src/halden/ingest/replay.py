"""Replay history in three steps and prove the result equals a single full load.

    python -m halden.ingest.replay [--db data/replay.duckdb] [--compare data/warehouse.duckdb]

Step 1 stops at 06:00 UTC on 14 September 2024, the morning after the processor file for
12 September should have arrived and did not. Step 2 stops at 06:00 UTC on 23 October 2024,
when the 21 October file is overdue. Step 3 sees everything. The arrivals table must say
"missing" for each day at the time, then "late" once the file turns up, and the final
tables must match the full load row for row.
"""
from __future__ import annotations

import argparse
import logging
import sys
from datetime import datetime, timezone
from pathlib import Path

import duckdb

from halden.common.log import setup_logging

from .pipeline import run

log = logging.getLogger("halden.ingest.replay")
STOPS = [datetime(2024, 9, 14, 6, tzinfo=timezone.utc), datetime(2024, 10, 23, 6, tzinfo=timezone.utc), None]
WATCH = ["2024-09-12", "2024-10-21"]
TABLES = ["int_orders", "int_transactions", "int_shipments", "mart_revenue_monthly", "mart_revenue_bridge_monthly",
          "mart_orders_monthly", "mart_deliveries_monthly"]


def replay(raw: Path, db: Path, compare: Path, out: Path) -> bool:
    if db.exists():
        db.unlink()   # a replay always starts from an empty warehouse
    lines = ["# As-of replay", "", "Generated by `python -m halden.ingest.replay`. Synthetic data.", "",
             "| Run | Sees files received up to | Files visible | Files loaded | Seconds | "
             "Processor 12 Sep 2024 | Processor 21 Oct 2024 |", "|---|---|---|---|---|---|---|"]
    for stop in STOPS:
        stats = run(raw, db, stop)
        con = duckdb.connect(str(db), read_only=True)
        status = dict(con.execute(
            "SELECT strftime(period_start, '%Y-%m-%d'), arrival_status || coalesce(' (' || hours_late || ' h)', '') "
            "FROM mart_file_arrivals WHERE source = 'payproc' AND strftime(period_start, '%Y-%m-%d') IN (?, ?)",
            WATCH).fetchall())
        con.close()
        when = stop.strftime("%Y-%m-%d %H:%M UTC") if stop else "everything"
        lines.append(f"| {stats['run_id']} | {when} | {stats['files_seen']:,} | {stats['files_loaded']:,} | "
                     f"{stats['seconds']} | {status.get(WATCH[0], 'not_yet_due')} | {status.get(WATCH[1], 'not_yet_due')} |")
    con = duckdb.connect(str(db), read_only=True)
    con.execute(f"ATTACH '{compare}' AS full_load (READ_ONLY)")
    lines += ["", f"Final tables compared with a single full load (`{compare}`):", "",
              "| Table | Rows | Only in replay | Only in full load |", "|---|---|---|---|"]
    ok = True
    for t in TABLES:
        n = con.execute(f"SELECT count(*) FROM {t}").fetchone()[0]
        a = con.execute(f"SELECT count(*) FROM (SELECT * FROM {t} EXCEPT ALL SELECT * FROM full_load.{t})").fetchone()[0]
        b = con.execute(f"SELECT count(*) FROM (SELECT * FROM full_load.{t} EXCEPT ALL SELECT * FROM {t})").fetchone()[0]
        ok &= a == b == 0
        lines.append(f"| {t} | {n:,} | {a} | {b} |")
    con.close()
    lines += ["", "Result: " + ("PASS, the incremental replay and the full load are identical." if ok
                                else "FAIL, the replay and the full load differ.")]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    log.info("replay %s; written to %s", "PASS" if ok else "FAIL", out)
    return ok


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m halden.ingest.replay")
    ap.add_argument("--raw", type=Path, default=Path("data/raw"))
    ap.add_argument("--db", type=Path, default=Path("data/replay.duckdb"))
    ap.add_argument("--compare", type=Path, default=Path("data/warehouse.duckdb"))
    ap.add_argument("--out", type=Path, default=Path("project_01_ingestion/validation/replay.md"))
    a = ap.parse_args(argv)
    setup_logging()
    return 0 if replay(a.raw, a.db, a.compare, a.out) else 1


if __name__ == "__main__":
    sys.exit(main())
