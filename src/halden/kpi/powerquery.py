"""Write the Power Query (M) scripts that load the KPI files into Excel.

The scripts are generated from the files themselves, so a column added to an export can never
be missing from its query. Each script:

- reads the path from the workbook's `DataFolder` cell, so the pack works from any folder,
  with Windows (`C:\\...`) or Mac (`/Users/...`) paths;
- reads UTF-8 explicitly, because Excel's default for CSV is the Windows code page;
- types every column with the en-US culture, so "0.03869" is read the same on a PC set to
  German or Arabic regional settings, where the decimal separator is a comma;
- stops with an error if the columns in the file are not the ones it expects, instead of
  loading a shifted table that looks fine.
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

# Excel sheet each query loads to, and the order the setup macro runs them in.
QUERIES = {
    "kpi_monthly": ("kpi_monthly.csv", "Data_Monthly"),
    "kpi_country_monthly": ("kpi_country_monthly.csv", "Data_Country"),
    "revenue_bridge_monthly": ("revenue_bridge_monthly.csv", "Data_Bridge"),
    "kpi_manifest": ("_manifest.csv", "Data_Manifest"),
}
TEXT_COLUMNS = {"month", "country_code", "file_name", "control_column", "sha256"}


def m_type(col: str, dtype) -> str:
    if col in TEXT_COLUMNS:
        return "type text"
    if pd.api.types.is_integer_dtype(dtype):
        return "Int64.Type"
    return "type number"


def m_script(file_name: str, df: pd.DataFrame) -> str:
    cols = list(df.columns)
    expected = ", ".join(f'"{c}"' for c in cols)
    types = ",\n        ".join(f'{{"{c}", {m_type(c, df[c].dtype)}}}' for c in cols)
    sort_cols = [c for c in ("month", "country_code", "file_name") if c in cols]
    sort = ", ".join(f'{{"{c}", Order.Ascending}}' for c in sort_cols)
    return f"""// Generated by `python -m halden.kpi extract`. Do not edit by hand; edit powerquery.py.
// Loads {file_name}. Synthetic data.
let
    Folder = Text.TrimEnd(Excel.CurrentWorkbook(){{[Name = "DataFolder"]}}[Content]{{0}}[Column1], {{"\\", "/"}}),
    // Windows paths use \, Mac paths use /. Join with whichever the folder cell uses.
    Separator = if Text.Contains(Folder, "/") then "/" else "\\",
    Source = Csv.Document(
        File.Contents(Folder & Separator & "{file_name}"),
        [Delimiter = ",", Encoding = 65001, QuoteStyle = QuoteStyle.Csv]
    ),
    Promoted = Table.PromoteHeaders(Source, [PromoteAllScalars = false]),
    Expected = {{{expected}}},
    Checked =
        if Table.ColumnNames(Promoted) = Expected then Promoted
        else error Error.Record(
            "Unexpected columns in {file_name}",
            "Expected: " & Text.Combine(Expected, ", "),
            "Found: " & Text.Combine(Table.ColumnNames(Promoted), ", ")
        ),
    Typed = Table.TransformColumnTypes(Checked, {{
        {types}
    }}, "en-US"),
    Sorted = Table.Sort(Typed, {{{sort}}})
in
    Sorted
"""


def write_scripts(data: Path, out: Path) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    paths = []
    for query, (file_name, _sheet) in QUERIES.items():
        df = pd.read_csv(data / file_name, dtype={c: str for c in TEXT_COLUMNS})
        p = out / f"{query}.pq"
        p.write_text(m_script(file_name, df), encoding="utf-8", newline="\r\n")
        paths.append(p)
    return paths
